"""What would have to be true for the 23 soft-core definitions to be covered.

`softcore.py` identifies 23 definitions that are simultaneously

    SINGLE-TIER   no other checking layer touches them
    CONJECTURED   the bound graded against is inferred from the definition's
                  name or docstring, not proved by any theorem
    ONE-MUTANT    the check rejects exactly one of the nearby wrong bodies tried

They are covered in name only.  This module says, per definition, what would
have to exist for that to stop being true -- so whoever picks one up builds the
missing thing rather than rediscovering which thing is missing.

HOW TO READ IT.  Each axis fails for a different reason and needs a different
fix, and fixing one does not fix the others:

  SINGLE-TIER is fixed by a SECOND TIER evaluating the definition at all.  It
      is not fixed by strengthening my check, however much I strengthen it.  A
      single tier that is wrong about a definition is wrong about it alone.

  CONJECTURED is fixed by a THEOREM in the corpus stating the bound, after
      which the same check becomes theorem-graded and a violation becomes a
      defect rather than a lead.  It is NOT fixed by me choosing a better
      range: any range I choose is still my reading of the name.  This is the
      cheapest of the three to fix and the one that most changes what the
      coverage number means -- it converts "conforms to my reading of its name"
      into "conforms to what the development asserts".

  ONE-MUTANT is fixed by a check with more DISCRIMINATING POWER over the same
      body.  A nonnegativity check on an unbounded-above quantity can only ever
      reject sign errors, so it kills one mutant out of six however many
      mutants are tried.  The fix is an invariant with more structure --
      monotonicity in a named argument, a limit, an identity against a second
      definition, or a value at a known point.

WHAT THIS FILE IS NOT.  It is not a claim that these 23 are wrong.  Nothing here
found a defect in any of them.  It is a statement that if one WERE wrong, the
current evidence would probably not notice, which is a different and more
useful thing to record.

STATUS.  Compiled without local execution (no compute is permitted on this
machine).  The axis assignments come from softcore.json, which was generated by
a verified run.  The per-definition notes below are grounded in the Lean source
where marked READ, and inferred from the definition's name and check record
where marked INFERRED.  Anything INFERRED should be confirmed against the body
before acting on it.  One concrete item to check first is recorded in
OPEN_QUESTIONS.
"""
