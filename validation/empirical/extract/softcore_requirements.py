UPGRADE_PATHS = {
    "single_tier": (
        "Any second tier producing a verdict on the definition. The differential "
        "tier needs an independent analytic reference or a simulation; the range "
        "tier needs the body inside its arithmetic fragment; the symbolic tier "
        "needs it to participate in an identity or a fixed point. Cheapest is "
        "usually the range tier, since it already parses everything this table "
        "parses."
    ),
    "conjectured_bound": (
        "A Lean theorem stating the bound under explicit hypotheses, e.g. "
        "`theorem f_in_unit (h : ...) : 0 <= f x /\\ f x <= 1`. The accounting "
        "then mines it automatically: `range_lo_thm` / `range_hi_thm` populate, "
        "`source_lo` / `source_hi` become \"theorem\", and a violation is "
        "reclassified from RANGE-MISMATCH to DEFECT. No change to this tier is "
        "needed -- the check already exists and is already falsifiable; only its "
        "authority is missing."
    ),
    "one_mutant": (
        "An invariant with more discriminating power over the same body. In "
        "rough order of cost: (a) monotonicity in one named argument, which "
        "kills every mutant that changes the sign of a partial derivative; "
        "(b) a value at a distinguished point (f at 0, at 1, at the equilibrium) "
        "which kills constant-factor and off-by-one mutants; (c) an identity "
        "against a second definition, which is the strongest and is what the "
        "strong core has."
    ),
}

